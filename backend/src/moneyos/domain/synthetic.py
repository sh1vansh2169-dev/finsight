"""Deterministic synthetic statements for demos and tests.

Everything here is invented: the bank, merchants, account numbers and
amounts. The dataset is deliberately messy (three different layouts,
overlapping date ranges, unparseable rows, transactions no rule can
classify) and comes with the ground truth the pipeline is expected to
recover, computed from the generated ledger rather than by running the
pipeline.
"""

from __future__ import annotations

import csv
import io
import random
from collections import Counter
from dataclasses import dataclass
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

SAMPLE_MARKER = "SYNTHETIC SAMPLE DATA - NOT REAL TRANSACTIONS"
_MONTH_ABBR = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")
_SAVINGS_ACCOUNT = "Sample Savings 0001"
CARD_ACCOUNT = "Sample Card 4321"  # suggested --account for the card file
PAYAPP_ACCOUNT = "Sample PayApp"  # suggested --account for the payment-app export
# Bank description -> how the payment app names the same merchant.
_APP_NAMES = {
    "FRESHMART GROCERIES": "FreshMart",
    "SPICE ROUTE RESTAURANT": "Spice Route",
    "CHAI POINT CAFE": "Chai Point",
    "QUICKCAB RIDE": "QuickCab",
    "METRO CARD RECHARGE": "Metro Card",
}
_OVERLAP_START, _OVERLAP_END = date(2026, 2, 1), date(2026, 2, 15)
# (description, min rupees, max rupees)
_VARIABLE_SPEND = (
    ("FRESHMART GROCERIES", 300, 2500),
    ("SPICE ROUTE RESTAURANT", 400, 1800),
    ("CHAI POINT CAFE", 40, 95),
    ("METRO CARD RECHARGE", 200, 500),
    ("QUICKCAB RIDE", 120, 650),
)
_CARD_SPEND = (
    ("SHOPKART ONLINE STORE", 500, 4000),
    ("WELLCARE PHARMACY", 150, 900),
    ("PETRO FUEL STATION", 800, 2500),
)


@dataclass(frozen=True, slots=True)
class _Entry:
    day: date
    description: str
    amount: Decimal
    # What the rules are expected to infer: expense, income, refund,
    # transfer or unknown.
    kind: str = "expense"


@dataclass(frozen=True, slots=True)
class Expected:
    unique_transactions: int
    duplicates: int
    suspected_duplicates: int
    rejected: int
    blank_rows: int
    income: Decimal
    expenses: Decimal
    refunds: Decimal
    unclassified_inflow: Decimal
    unclassified_outflow: Decimal
    transfers_in: Decimal
    transfers_out: Decimal

    @property
    def net_cash_flow(self) -> Decimal:
        inflow = self.income + self.refunds + self.unclassified_inflow
        outflow = self.expenses + self.unclassified_outflow
        return inflow - outflow


@dataclass(frozen=True, slots=True)
class MirroredPayment:
    """Ground truth: an app payment that is the same money as a bank entry."""

    app_reference: str
    bank_date: date
    bank_description: str
    amount: Decimal


@dataclass(frozen=True, slots=True)
class PayAppExport:
    """A payment-app history for the same savings account.

    Some payments also appear in the bank statement (true cross-source
    duplicates, listed in ``mirrored``); some were paid from an account
    MoneyOS has not seen (``app_only``); some failed (``failed``).
    """

    name: str
    text: str
    mirrored: tuple[MirroredPayment, ...]
    app_only: int
    failed: int


@dataclass(frozen=True, slots=True)
class SyntheticDataset:
    files: dict[str, str]  # statement file name -> CSV text, in import order
    expected: Expected  # for the statement files alone
    payapp: PayAppExport

    def write(self, directory: str | Path) -> list[Path]:
        """Write all files; return the statement paths (not the app export)."""
        directory = Path(directory)
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "README.txt").write_text(
            f"{SAMPLE_MARKER}\nGenerated by `moneyos sample`. Every bank, merchant, "
            "account and amount in these files is invented.\n",
            encoding="utf-8",
        )
        paths = []
        for name, text in self.files.items():
            path = directory / name
            path.write_text(text, encoding="utf-8", newline="")
            paths.append(path)
        (directory / self.payapp.name).write_text(self.payapp.text, encoding="utf-8", newline="")
        return paths


def _rupees(rng: random.Random, low: int, high: int) -> Decimal:
    return Decimal(rng.randint(low * 100, high * 100)) / 100


def _indian_grouping(value: Decimal) -> str:
    whole, _, fraction = f"{abs(value):.2f}".partition(".")
    head, tail = whole[:-3], whole[-3:]
    groups = []
    while head:
        groups.insert(0, head[-2:])
        head = head[:-2]
    return ",".join([*groups, tail]) + "." + fraction


def _savings_ledger(rng: random.Random) -> list[_Entry]:
    entries: list[_Entry] = []
    used = set()

    def add(day, description, amount, kind="expense", *, allow_repeat=False) -> bool:
        key = (day, description, amount)
        if key in used and not allow_repeat:
            return False
        used.add(key)
        entries.append(_Entry(day, description, amount, kind))
        return True

    for month in (1, 2, 3):
        add(date(2026, month, 1), "ACME CORP SALARY", Decimal("85000.00"), "income")
        add(date(2026, month, 3), "RENT PAYMENT GREENVIEW APTS", Decimal("-22000.00"))
        add(date(2026, month, 10), "CITY POWER ELECTRICITY BILL", -_rupees(rng, 900, 2400))
        add(date(2026, month, 12), "FIBERNET BROADBAND", Decimal("-999.00"))
        add(date(2026, month, 20), "TRANSFER TO CREDIT CARD 4321", -_rupees(rng, 3000, 9000), "transfer")
        added = 0
        while added < 8:
            description, low, high = rng.choice(_VARIABLE_SPEND)
            added += add(date(2026, month, rng.randint(2, 28)), description, -_rupees(rng, low, high))

    add(date(2026, 3, 25), "ANNUAL BONUS ACME CORP", Decimal("125000.00"), "income")
    # No rule can tell what these are, so they must stay unclassified.
    add(date(2026, 3, 9), "UPI/P2P/FRIEND-7731", Decimal("-1500.00"), "unknown")
    add(date(2026, 3, 17), "NEFT CR 88231 ANON", Decimal("2750.00"), "unknown")
    # Two genuinely separate, identical purchases inside the overlap window.
    for _ in range(2):
        add(date(2026, 2, 7), "CHAI POINT CAFE", Decimal("-120.00"), allow_repeat=True)

    return sorted(entries, key=lambda e: e.day)


def _card_ledger(rng: random.Random) -> list[_Entry]:
    entries = []
    for month in (1, 2, 3):
        entries.append(_Entry(date(2026, month, 5), "STREAMFLIX SUBSCRIPTION", Decimal("-649.00")))
        for description, low, high in _CARD_SPEND:
            entries.append(_Entry(date(2026, month, rng.randint(6, 19)), description, -_rupees(rng, low, high)))
        entries.append(
            _Entry(date(2026, month, 21), "PAYMENT RECEIVED THANK YOU", _rupees(rng, 3000, 9000), "transfer")
        )
    entries.append(_Entry(date(2026, 2, 24), "SHOPKART REFUND", Decimal("499.00"), "refund"))
    return sorted(entries, key=lambda e: e.day)


def _csv_text(header: list[str], rows: list[list[str]]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue()


def _total(entries, kind: str, *, sign: int) -> Decimal:
    return abs(sum((e.amount for e in entries if e.kind == kind and (e.amount > 0) == (sign > 0)), Decimal(0)))


def generate(seed: int = 2026) -> SyntheticDataset:
    """Build three synthetic statement files plus the expected import outcome."""
    rng = random.Random(seed)
    savings = _savings_ledger(rng)
    card = _card_ledger(rng)

    # File 1: 1 Jan - 15 Feb. DD/MM/YYYY dates, one signed amount column.
    first = [
        [e.day.strftime("%d/%m/%Y"), e.description, str(e.amount), _SAVINGS_ACCOUNT]
        for e in savings
        if e.day <= _OVERLAP_END
    ]
    first += [
        ["31/02/2026", "FRESHMART GROCERIES", "-450.00", _SAVINGS_ACCOUNT],  # no such date
        ["14/01/2026", "QUICKCAB RIDE", "abc", _SAVINGS_ACCOUNT],  # bad amount
        ["", "", "", ""],  # blank
    ]

    # File 2: 1 Feb - 31 Mar, same account, so 1-15 Feb overlaps file 1.
    # ISO dates, lower-case descriptions with stray spaces, split
    # withdrawal/deposit columns with a rupee sign and Indian grouping.
    second = []
    for e in savings:
        if e.day < _OVERLAP_START:
            continue
        money = "₹" + _indian_grouping(e.amount)
        second.append([
            e.day.isoformat(),
            "  " + e.description.lower().replace(" ", "  "),
            money if e.amount < 0 else "",
            money if e.amount > 0 else "",
            _SAVINGS_ACCOUNT,
        ])
    second.append(["2026-03-15", "", "₹250.00", "", _SAVINGS_ACCOUNT])  # no description

    # File 3: credit card. Named-month dates, unsigned amount with a DR/CR
    # column, bank reference numbers, no account column (so the importer
    # must be told the account name, or falls back to the file name).
    third = [
        [
            f"{e.day.day:02d} {_MONTH_ABBR[e.day.month - 1]} {e.day.year}",
            e.description,
            f"{abs(e.amount):,.2f}",
            "CR" if e.amount > 0 else "DR",
            f"CC{number:06d}",
        ]
        for number, e in enumerate(card, start=1)
    ]
    third.append(list(third[3]))  # same reference exported twice
    third.append(["18 Mar 2026", "WELLCARE PHARMACY", "", "DR", "CC999999"])  # no amount

    overlap = sum(1 for e in savings if _OVERLAP_START <= e.day <= _OVERLAP_END)
    ledger = [*savings, *card]
    expected = Expected(
        unique_transactions=len(ledger),
        duplicates=overlap + 1,
        suspected_duplicates=1,
        rejected=4,
        blank_rows=1,
        income=_total(ledger, "income", sign=1),
        expenses=_total(ledger, "expense", sign=-1),
        refunds=_total(ledger, "refund", sign=1),
        unclassified_inflow=_total(ledger, "unknown", sign=1),
        unclassified_outflow=_total(ledger, "unknown", sign=-1),
        transfers_in=_total(ledger, "transfer", sign=1),
        transfers_out=_total(ledger, "transfer", sign=-1),
    )
    files = {
        "sample_savings_2026-01-01_to_02-15.csv": _csv_text(
            ["Date", "Description", "Amount", "Account"], first
        ),
        "sample_savings_2026-02-01_to_03-31.csv": _csv_text(
            ["Txn Date", "Narration", "Withdrawal", "Deposit", "Account"], second
        ),
        "sample_card_4321_2026_q1.csv": _csv_text(
            ["Posting Date", "Merchant", "Amount", "Type", "Ref No"], third
        ),
    }
    return SyntheticDataset(files=files, expected=expected, payapp=_payapp(savings, seed))


def _app_time(rng: random.Random, day: date) -> str:
    hour, minute = rng.randint(8, 21), rng.randint(0, 59)
    return (
        f"{day.day:02d} {_MONTH_ABBR[day.month - 1]} {day.year}, "
        f"{hour % 12 or 12}:{minute:02d} {'AM' if hour < 12 else 'PM'}"
    )


def _payapp(savings: list[_Entry], seed: int) -> PayAppExport:
    # A separate random stream, so adding this file left the statements unchanged.
    rng = random.Random(seed + 1)
    repeats = Counter((e.day, e.description, e.amount) for e in savings)
    rows: list[tuple[date, str, Decimal, str, str]] = []
    mirrored = []

    def reference() -> str:
        return f"PA{len(rows) + 1:07d}"

    for e in savings:
        # Identical repeated entries are skipped: which one an app row would
        # mirror is unknowable, so they make poor ground truth.
        if e.description not in _APP_NAMES or repeats[(e.day, e.description, e.amount)] > 1:
            continue
        if rng.random() >= 0.5:
            continue
        ref = reference()
        # The app shows when you paid; the bank may post it a day later.
        app_day = e.day - timedelta(days=rng.choice((0, 0, 1)))
        rows.append((app_day, _APP_NAMES[e.description], e.amount, "SUCCESS", ref))
        mirrored.append(MirroredPayment(ref, e.day, e.description, e.amount))

    # Paid from an account MoneyOS has not seen: real money, no bank copy.
    # The 12 Feb one is a decoy: same day and amount as the bank's broadband
    # bill, but a different merchant. It must not be proposed as a duplicate.
    app_only = ((date(2026, 1, 18), "-340.00"), (date(2026, 2, 12), "-999.00"), (date(2026, 3, 14), "-410.00"))
    for day, amount in app_only:
        rows.append((day, "Corner Kirana Store", Decimal(amount), "SUCCESS", reference()))
    failed = ((date(2026, 2, 9), "-899.00"), (date(2026, 3, 2), "-1250.00"))
    for day, amount in failed:
        rows.append((day, "Spice Route", Decimal(amount), "FAILED", reference()))

    rows.sort(key=lambda r: (r[0], r[4]))
    text = _csv_text(
        ["Date", "Paid to / Received from", "Amount", "Type", "Status", "UPI Ref No"],
        [
            [_app_time(rng, day), name, f"₹{abs(amount):,.2f}", "Debit" if amount < 0 else "Credit", status, ref]
            for day, name, amount, status, ref in rows
        ],
    )
    return PayAppExport(
        name="sample_payapp_2026_q1.csv",
        text=text,
        mirrored=tuple(mirrored),
        app_only=len(app_only),
        failed=len(failed),
    )
